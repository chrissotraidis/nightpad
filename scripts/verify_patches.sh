#!/bin/sh
set -eu

# Proves the tracked patch series reproduces the vendor tree: apply every
# patch to a clean worktree at the pinned revision, then compare the files with
# the working checkout. Fails if the vendor has changes no patch covers.
repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
vendor="$repo/vendor/nightfire"
pin=$(python3 -c "import json;print(json.load(open('$repo/config/dependencies.lock.json'))['source_graph']['nightfire']['revision'])")
tmp=$(mktemp -d /tmp/nightpad-patch-check.XXXXXX)
applied=$(mktemp /tmp/nightpad-applied.XXXXXX)
present=$(mktemp /tmp/nightpad-present.XXXXXX)

cleanup() {
    git -C "$vendor" worktree remove --force "$tmp" >/dev/null 2>&1 || true
    rm -f "$applied" "$present"
}
trap cleanup EXIT INT TERM

git -C "$vendor" worktree add --detach "$tmp" "$pin" >/dev/null 2>&1
for patch in "$repo"/patches/00*.patch; do
    git -C "$tmp" apply "$patch" || {
        echo "verify_patches: $patch does not apply to $pin" >&2
        exit 1
    }
done

git -C "$tmp" status --porcelain | sed 's/^...//' | sort > "$applied"
# The linker map files are regenerated by every build, not owned by a patch.
git -C "$vendor" status --porcelain | sed 's/^...//' | grep -v -e '^build/' -e '\.map$' | sort > "$present" || true

if ! diff -u "$applied" "$present" >/dev/null; then
    echo "verify_patches: vendor changes and the patch series differ:" >&2
    diff -u "$applied" "$present" >&2 || true
    exit 1
fi

while IFS= read -r file; do
    [ -n "$file" ] || continue
    if ! cmp -s "$tmp/$file" "$vendor/$file"; then
        echo "verify_patches: $file differs from the patched pin" >&2
        exit 1
    fi
done < "$applied"

count=$(wc -l < "$applied" | tr -d ' ')
echo "verify_patches: PASS ($count files reproduced from $pin)"
